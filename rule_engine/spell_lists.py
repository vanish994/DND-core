def _normalizar(valor: object) -> str:
    import re
    import unicodedata

    texto = unicodedata.normalize("NFKD", str(valor).strip().lower())
    texto = "".join(c for c in texto if not unicodedata.combining(c))
    return re.sub(r"\s+", " ", texto).replace("-", " ")


def listar_magias_da_classe(classe: str, circulo: int | None = None) -> list[str]:
    """Nomes das magias da classe (PHB 2024), opcionalmente por círculo."""
    tabela = LISTAS_POR_CLASSE.get(_normalizar(classe))
    if tabela is None:
        raise ValueError(f"classe conjuradora desconhecida: {classe!r}")
    if circulo is None:
        return [nome for c in sorted(tabela) for nome in tabela[c]]
    return list(tabela.get(int(circulo), ()))


def magia_na_lista(nome: str, classe: str, circulo: int | None = None) -> bool:
    """Verifica se a magia consta da lista da classe (e círculo, se dado)."""
    chave = _normalizar(nome)
    return any(_normalizar(n) == chave for n in listar_magias_da_classe(classe, circulo))
